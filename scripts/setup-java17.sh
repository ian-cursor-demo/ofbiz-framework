#!/usr/bin/env bash
# Install JDK 17 for this project only (writes gitignored .java-env; does not touch ~/.zshrc).
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
JAVA_ENV="${REPO_ROOT}/.java-env"
BREW_JDK_HOME="/opt/homebrew/opt/openjdk@17/libexec/openjdk.jdk/Contents/Home"
INTEL_BREW_JDK_HOME="/usr/local/opt/openjdk@17/libexec/openjdk.jdk/Contents/Home"

java_major_version() {
  local java_bin="$1"
  local ver major
  ver="$("${java_bin}" -version 2>&1 | awk -F '"' '/version/ {print $2; exit}')"
  if [[ "${ver}" == 1.* ]]; then
    major="${ver#1.}"
    major="${major%%.*}"
  else
    major="${ver%%.*}"
  fi
  echo "${major}"
}

is_jdk17_home() {
  local home="$1"
  [[ -x "${home}/bin/java" ]] && [[ "$(java_major_version "${home}/bin/java")" == "17" ]]
}

resolve_java17_home() {
  local candidates=()
  [[ -d "${BREW_JDK_HOME}" ]] && candidates+=("${BREW_JDK_HOME}")
  [[ -d "${INTEL_BREW_JDK_HOME}" ]] && candidates+=("${INTEL_BREW_JDK_HOME}")
  if command -v /usr/libexec/java_home >/dev/null 2>&1; then
    local jh
    if jh="$(/usr/libexec/java_home -v 17 2>/dev/null)"; then
      candidates+=("${jh}")
    fi
  fi
  local candidate
  for candidate in "${candidates[@]}"; do
    if is_jdk17_home "${candidate}"; then
      echo "${candidate}"
      return 0
    fi
  done
  return 1
}

if ! resolve_java17_home >/dev/null; then
  echo "[setup-java17] Installing openjdk@17 via Homebrew..."
  if ! command -v brew >/dev/null 2>&1; then
    echo "Homebrew not found. Install JDK 17 manually, then re-run this script." >&2
    exit 1
  fi
  brew install openjdk@17
fi

JAVA17_HOME="$(resolve_java17_home)" || {
  echo "JDK 17 not found after install. Try:" >&2
  echo "  sudo ln -sfn /opt/homebrew/opt/openjdk@17/libexec/openjdk.jdk /Library/Java/JavaVirtualMachines/openjdk-17.jdk" >&2
  exit 1
}

cat > "${JAVA_ENV}" <<EOF
# Project-local Java 17 for OFBiz (generated by scripts/setup-java17.sh; do not commit)
export JAVA_HOME="${JAVA17_HOME}"
export PATH="\${JAVA_HOME}/bin:\${PATH}"
export GRADLE_OPTS="-Dorg.gradle.java.home=\${JAVA_HOME} \${GRADLE_OPTS:-}"
EOF

echo "[setup-java17] Wrote ${JAVA_ENV}"
echo "[setup-java17] JAVA_HOME=${JAVA17_HOME}"
"${JAVA17_HOME}/bin/java" -version
